// Maintainer-only: refresh the offline builder's read-only data snapshot.
// The browser page itself is plain HTML/CSS/JS and needs no server or install.
const fs = require('node:fs');
const path = require('node:path');
const { editableFiles } = require('./validation.js');

const root = path.resolve(__dirname, '../..');
const originalFiles = Object.fromEntries(Object.values(editableFiles).map(name => [
  name, fs.readFileSync(path.join(root, name), 'utf8'),
]));
const metadata = JSON.parse(fs.readFileSync(path.join(root, 'src/data/metadata.json'), 'utf8'));
const verseDirectory = path.join(root, 'src/data/verses');
const verseFiles = fs.readdirSync(verseDirectory).filter(name => /^\d{3}_\d{3}\.json$/.test(name)).sort();
if (metadata.length !== 114 || verseFiles.length !== 6236) throw new Error('Quran reference data is incomplete');
const verses = {};
for (const name of verseFiles) {
  const chapter = Number(name.slice(0, 3));
  const ayah = Number(name.slice(4, 7));
  const text = JSON.parse(fs.readFileSync(path.join(verseDirectory, name), 'utf8')).text?.ar;
  if (!text) throw new Error(`Missing Arabic text: ${name}`);
  verses[`${chapter}:${ayah}`] = text;
}
const assetDirectory = path.join(root, 'public/discovery-images');
const assets = fs.readdirSync(assetDirectory)
  .filter(name => /^[a-zA-Z0-9_-]+\.webp$/.test(name))
  .sort()
  .map(name => `public/discovery-images/${name}`);
const output = { version: 1, originalFiles, metadata, verses, assets };
fs.writeFileSync(path.join(__dirname, 'data-snapshot.js'),
  `// Generated by build-snapshot.cjs. Do not edit by hand.\nwindow.BuilderSnapshot = ${JSON.stringify(output)};\n`);
console.log(`Updated offline builder snapshot: ${verseFiles.length} ayat, ${assets.length} images.`);
